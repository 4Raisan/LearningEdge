/**
 * Converts a raw SQLite KnowledgeGraphSnapshot into an interactive GraphDomain.
 */
export function convertSnapshotToDomain(
  snapshot: KnowledgeGraphSnapshot,
  domainName: string = "Personal Lecture Vault"
): GraphDomain {
  if (!snapshot.concepts || snapshot.concepts.length === 0) {
    return {
      ...AI_KNOWLEDGE_DOMAIN,
      id: "domain-empty-fallback",
      name: "Knowledge Graph (Sample Vault)",
    };
  }

  // Find a central concept or pick the first
  const centralId = snapshot.concepts[0].id;

  const nodes: GraphNode[] = snapshot.concepts.map((c, idx) => {
    const isCentral = idx === 0;
    const category: NodeCategory = isCentral
      ? "central"
      : idx % 4 === 1
      ? "main"
      : idx % 4 === 2
      ? "subtopic"
      : idx % 4 === 3
      ? "related"
      : "supporting";

    const importance = isCentral ? 5 : ((4 - (idx % 3)) as 1 | 2 | 3 | 4 | 5);
    const link = c.links && c.links.length > 0 ? c.links[0] : undefined;

    return {
      id: c.id,
      label: c.label,
      category,
      importance,
      summary: c.summary.slice(0, 140),
      description: c.summary,
      mastered: idx % 3 === 0, // Sample distribution
      aliases: c.aliases,
      lectureId: link?.lecture_id,
      notePointId: link?.note_point_id ?? undefined,
      sourceRefs: link?.source_refs ?? [],
      videoStartMs: link?.video_start_ms ?? undefined,
      videoEndMs: link?.video_end_ms ?? undefined,
      x: 0,
      y: 0,
      vx: 0,
      vy: 0,
      radius: isCentral ? 38 : category === "main" ? 28 : category === "subtopic" ? 22 : 18,
    };
  });

  const edges: GraphEdge[] = snapshot.edges.map((e) => {
    let rel: EdgeRelation = "leads_to";
    if (e.relation === "contains") rel = "contains";
    else if (e.relation === "depends_on") rel = "depends_on";
    else if (e.relation === "related_to" || e.relation === "related_mechanism") rel = "related_to";
    else if (e.relation === "part_of") rel = "part_of";
    else if (e.relation === "example_of") rel = "example_of";
    else if (e.relation === "applied_in") rel = "applied_in";

    return {
      id: e.id,
      source: e.from_concept_id,
      target: e.to_concept_id,
      relation: rel,
      label: rel.replace("_", " "),
      supportingSources: e.supporting_sources,
    };
  });

  return {
    id: "domain-personal-vault",
    name: domainName,
    description: `Personal learning graph containing ${nodes.length} concepts and ${edges.length} relationships recorded across your lectures.`,
    icon: "book",
    centralNodeId: centralId,
    nodes,
    edges,
  };
}
